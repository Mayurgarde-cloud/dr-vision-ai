"""Generate a synthetic 231-image demo dataset (class folders under data/dataset/).

    python -m scripts.make_sample_dataset [--size 256] [--out data/dataset]

The images are illustrative, NOT real fundus photographs. They let you try the Dataset page,
the training pipeline and the evaluation page without downloading anything. Replace them with
EyePACS / APTOS / Messidor images for real experiments.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ml.synthetic import make_fundus  # noqa: E402

FOLDERS = ["0_No_DR", "1_Mild_DR", "2_Moderate_DR", "3_Severe_DR", "4_Proliferative_DR"]
COUNTS = [97, 46, 42, 28, 18]   # 231 images


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "data" / "dataset"))
    ap.add_argument("--size", type=int, default=256)
    ap.add_argument("--quality", type=int, default=88)
    args = ap.parse_args()
    out = Path(args.out)
    for sev, (folder, n) in enumerate(zip(FOLDERS, COUNTS)):
        d = out / folder
        d.mkdir(parents=True, exist_ok=True)
        for i in range(n):
            make_fundus(sev, seed=20000 + i, size=args.size).save(d / f"synthetic_{sev}_{i:03d}.jpg", quality=args.quality)
        print(f"{folder}: {n} images")
    (out / "dataset.json").write_text(json.dumps({
        "name": "Synthetic Demo Set",
        "source": "Generated by scripts/make_sample_dataset.py (not real patient data)"}, indent=2))
    print(f"Done – {sum(COUNTS)} images in {out}")


if __name__ == "__main__":
    main()
